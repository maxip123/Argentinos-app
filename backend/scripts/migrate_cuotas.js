process.env.NODE_TLS_REJECT_UNAUTHORIZED = '0';
require('dotenv').config();
const { Client } = require('pg');

const client = new Client({
  connectionString: process.env.DATABASE_URL,
  ssl: { rejectUnauthorized: false }
});

const migration = `
ALTER TABLE public.jugador
  ADD COLUMN IF NOT EXISTS fecha_ultimo_pago   TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS fecha_vencimiento   DATE,
  ADD COLUMN IF NOT EXISTS es_inactivo         BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS public.gasto_club (
    id_gasto    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concepto    VARCHAR(255) NOT NULL,
    monto       NUMERIC(12,2) NOT NULL CHECK (monto > 0),
    fecha_gasto TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    categoria   VARCHAR(50) DEFAULT 'General',
    activo      BOOLEAN NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.gasto_club ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE tablename = 'gasto_club'
    AND policyname = 'Acceso gastos solo autenticados'
  ) THEN
    CREATE POLICY "Acceso gastos solo autenticados" ON public.gasto_club
        FOR ALL TO authenticated USING (true) WITH CHECK (true);
  END IF;
END
$$;

CREATE INDEX IF NOT EXISTS idx_jugador_vencimiento
    ON public.jugador(fecha_vencimiento)
    WHERE es_inactivo = FALSE AND fecha_vencimiento IS NOT NULL;
`;

async function run() {
  try {
    await client.connect();
    console.log('✅ Conectado a Supabase');
    await client.query(migration);
    console.log('✅ Migración ejecutada correctamente');

    // Verificar columnas
    const { rows } = await client.query(`
      SELECT column_name, data_type 
      FROM information_schema.columns 
      WHERE table_schema = 'public' 
        AND table_name = 'jugador'
        AND column_name IN ('fecha_ultimo_pago', 'fecha_vencimiento', 'es_inactivo')
      ORDER BY column_name;
    `);
    console.log('📋 Columnas nuevas en jugador:', rows);

    const { rows: tablaGasto } = await client.query(`
      SELECT table_name FROM information_schema.tables 
      WHERE table_schema = 'public' AND table_name = 'gasto_club';
    `);
    console.log('📋 Tabla gasto_club:', tablaGasto.length > 0 ? 'CREADA ✅' : 'NO EXISTE ❌');
  } catch (err) {
    console.error('❌ Error:', err.message);
    process.exit(1);
  } finally {
    await client.end();
  }
}

run();
