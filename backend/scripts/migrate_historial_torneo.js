require('dotenv').config();
const { getPool } = require('../config/db');

async function applyHistorialTorneo() {
  const pool = getPool();
  try {
    console.log('⚡ Creando tabla historial_torneo en Supabase...');
    await pool.query(`
      CREATE TABLE IF NOT EXISTS public.historial_torneo (
          id_historial BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          id_division BIGINT REFERENCES public.division(id_division) ON DELETE SET NULL,
          nombre_torneo VARCHAR(150) NOT NULL,
          temporada INT NOT NULL,
          genero VARCHAR(20) NOT NULL,
          categoria VARCHAR(50),
          id_equipo_campeon BIGINT REFERENCES public.equipo(id_equipo) ON DELETE SET NULL,
          nombre_equipo_campeon VARCHAR(120),
          logo_campeon_url TEXT,
          es_campeon_argentinos BOOLEAN NOT NULL DEFAULT FALSE,
          fecha_finalizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
          
          -- Snapshots completos estructurados en JSONB
          tabla_posiciones     JSONB NOT NULL DEFAULT '[]'::jsonb,
          partidos_resultados  JSONB NOT NULL DEFAULT '[]'::jsonb,
          playoffs             JSONB NOT NULL DEFAULT '[]'::jsonb,
          goleadores_club      JSONB NOT NULL DEFAULT '[]'::jsonb,
          tarjetas_club        JSONB NOT NULL DEFAULT '[]'::jsonb,
          resumen_estadisticas JSONB NOT NULL DEFAULT '{}'::jsonb,
          
          observaciones TEXT,
          activo BOOLEAN NOT NULL DEFAULT TRUE,
          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );

      CREATE INDEX IF NOT EXISTS idx_historial_torneo_div ON public.historial_torneo(id_division, temporada DESC);

      ALTER TABLE public.historial_torneo ENABLE ROW LEVEL SECURITY;

      DO $$
      BEGIN
        IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'historial_torneo' AND policyname = 'Lectura publica historial_torneo') THEN
          CREATE POLICY "Lectura publica historial_torneo" ON public.historial_torneo FOR SELECT USING (true);
        END IF;

        IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'historial_torneo' AND policyname = 'Escritura autenticados historial_torneo') THEN
          CREATE POLICY "Escritura autenticados historial_torneo" ON public.historial_torneo FOR ALL TO authenticated USING (true) WITH CHECK (true);
        END IF;
      END $$;
    `);

    console.log('✅ Tabla historial_torneo creada con éxito.');
    const { rows } = await pool.query(`SELECT to_regclass('public.historial_torneo') as t;`);
    console.log('Verificación:', rows[0]);
    process.exit(0);
  } catch (err) {
    console.error('❌ Error creando historial_torneo:', err.message);
    process.exit(1);
  } finally {
    await pool.end();
  }
}

applyHistorialTorneo();
