/**
 * Cobros y deudas por concepto (reemplaza el modelo de cuota_jugador):
 * - concepto_cobro: catálogo (Cuota mensual, Inscripción, Seguro, ...), con monto sugerido.
 * - cargo_jugador: cada deuda de un jugador (mensual por período, o única con descripción).
 * - pago_cargo: pagos totales o parciales; 'Canje' salda sin entrar plata a la caja.
 * - gasto_club.id_pago: el movimiento de caja de cada pago que no es canje.
 * Nada se borra: deudas y pagos se anulan con motivo, autor y fecha.
 * Es idempotente. Uso: node scripts/migrate_cobros_conceptos.js
 */
require('dotenv').config({ path: require('path').join(__dirname, '../.env') });
const { getPool } = require('../config/db');

const migration = `
CREATE TABLE IF NOT EXISTS public.concepto_cobro (
    id_concepto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE,
    monto_sugerido NUMERIC(12,2) CHECK (monto_sugerido IS NULL OR monto_sugerido > 0),
    es_mensual BOOLEAN NOT NULL DEFAULT FALSE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.cargo_jugador (
    id_cargo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_jugador BIGINT NOT NULL REFERENCES public.jugador(id_jugador) ON DELETE RESTRICT,
    id_concepto BIGINT NOT NULL REFERENCES public.concepto_cobro(id_concepto) ON DELETE RESTRICT,
    id_equipo BIGINT REFERENCES public.equipo(id_equipo) ON DELETE SET NULL,
    periodo_mes INT CHECK (periodo_mes BETWEEN 1 AND 12),
    periodo_anio INT CHECK (periodo_anio BETWEEN 2000 AND 2100),
    descripcion VARCHAR(150),
    monto NUMERIC(12,2) NOT NULL CHECK (monto > 0),
    fecha_vencimiento DATE NOT NULL,
    no_corresponde BOOLEAN NOT NULL DEFAULT FALSE,
    motivo_no_corresponde TEXT,
    marcado_por UUID REFERENCES public.perfil_usuario(id_perfil) ON DELETE SET NULL,
    fecha_marcado TIMESTAMPTZ,
    creado_por UUID REFERENCES public.perfil_usuario(id_perfil) ON DELETE SET NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_cargo_periodo CHECK ((periodo_mes IS NULL) = (periodo_anio IS NULL))
);
-- Una sola cuota mensual por jugador y período, aunque esté en dos equipos
CREATE UNIQUE INDEX IF NOT EXISTS uq_cargo_mensual
    ON public.cargo_jugador(id_jugador, id_concepto, periodo_anio, periodo_mes)
    WHERE activo AND periodo_mes IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_cargo_jugador ON public.cargo_jugador(id_jugador) WHERE activo;
CREATE INDEX IF NOT EXISTS idx_cargo_equipo ON public.cargo_jugador(id_equipo) WHERE activo;

CREATE TABLE IF NOT EXISTS public.pago_cargo (
    id_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cargo BIGINT NOT NULL REFERENCES public.cargo_jugador(id_cargo) ON DELETE RESTRICT,
    monto NUMERIC(12,2) NOT NULL CHECK (monto > 0),
    fecha_pago DATE NOT NULL DEFAULT CURRENT_DATE,
    metodo_pago VARCHAR(20) NOT NULL
        CHECK (metodo_pago IN ('Efectivo', 'Transferencia', 'MercadoPago', 'Débito', 'Crédito', 'Otro', 'Canje')),
    observaciones TEXT,
    registrado_por UUID REFERENCES public.perfil_usuario(id_perfil) ON DELETE SET NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    motivo_anulacion TEXT,
    anulado_por UUID REFERENCES public.perfil_usuario(id_perfil) ON DELETE SET NULL,
    fecha_anulacion TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_pago_canje CHECK (metodo_pago <> 'Canje' OR length(trim(coalesce(observaciones, ''))) > 0)
);
CREATE INDEX IF NOT EXISTS idx_pago_cargo ON public.pago_cargo(id_cargo) WHERE activo;

ALTER TABLE public.gasto_club ADD COLUMN IF NOT EXISTS id_pago BIGINT REFERENCES public.pago_cargo(id_pago) ON DELETE RESTRICT;
CREATE INDEX IF NOT EXISTS idx_gasto_pago ON public.gasto_club(id_pago) WHERE id_pago IS NOT NULL;

ALTER TABLE public.concepto_cobro ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cargo_jugador ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pago_cargo ENABLE ROW LEVEL SECURITY;

INSERT INTO public.concepto_cobro (nombre, es_mensual) VALUES
    ('Cuota mensual', TRUE), ('Inscripción', FALSE), ('Seguro', FALSE),
    ('Indumentaria', FALSE), ('Aporte por partido', FALSE), ('Viaje', FALSE)
ON CONFLICT (nombre) DO NOTHING;
`;

async function main() {
  const pool = getPool();
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query(migration);
    const { rows } = await client.query('SELECT COUNT(*)::int AS n FROM public.concepto_cobro');
    await client.query('COMMIT');
    console.log(`Migración aplicada. Conceptos: ${rows[0].n}.`);
  } catch (err) {
    await client.query('ROLLBACK');
    throw err;
  } finally {
    client.release();
    await pool.end();
  }
}

main().catch((err) => {
  console.error('Error en la migración:', err.message);
  process.exit(1);
});
