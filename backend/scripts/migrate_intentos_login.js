/**
 * Límite de intentos de inicio de sesión.
 * intento_login guarda cada intento fallido (email + IP). El backend corre como función serverless,
 * así que el contador tiene que vivir en la base y no en memoria. Las filas se borran solas a las 24 h
 * (las limpia el propio login) y al iniciar sesión bien se borran las fallas de ese email desde esa IP.
 * Es idempotente. Uso: node scripts/migrate_intentos_login.js
 */
require('dotenv').config({ path: require('path').join(__dirname, '../.env') });
const { getPool } = require('../config/db');

const migration = `
CREATE TABLE IF NOT EXISTS public.intento_login (
    id_intento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    ip VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_intento_login_email_ip ON public.intento_login(email, ip, created_at);
CREATE INDEX IF NOT EXISTS idx_intento_login_ip ON public.intento_login(ip, created_at);
ALTER TABLE public.intento_login ENABLE ROW LEVEL SECURITY;
`;

async function main() {
  const pool = getPool();
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query(migration);
    await client.query('COMMIT');
    console.log('Migración aplicada: intento_login.');
  } catch (err) {
    await client.query('ROLLBACK');
    throw err;
  } finally {
    client.release();
    await pool.end();
  }
}

main().catch((err) => {
  console.error('Error en la migración:', err.message);
  process.exit(1);
});
