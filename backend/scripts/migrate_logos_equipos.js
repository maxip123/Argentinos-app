/**
 * Logos de equipos subidos desde el panel.
 * - equipo_logo guarda cada imagen subida como una fila propia (id_logo) que nunca se modifica ni se borra;
 *   se sirve en GET /api/equipos/logos/:id_logo. Los historiales archivados y los equipos copiados a otro
 *   torneo guardan esa ruta, así que no pierden el logo si el equipo después lo cambia.
 * - Los equipos que tenían el escudo del club fijo ('/gemini-svg.svg') pasan a NULL (= por defecto).
 * Si existe la primera versión de la tabla (una fila por equipo, sin id_logo) y está vacía, se reemplaza;
 * si tuviera filas, la migración se frena sin tocar nada.
 * Es idempotente. Uso: node scripts/migrate_logos_equipos.js
 */
require('dotenv').config({ path: require('path').join(__dirname, '../.env') });
const { getPool } = require('../config/db');

const migration = `
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'equipo_logo')
     AND NOT EXISTS (SELECT 1 FROM information_schema.columns
                     WHERE table_schema = 'public' AND table_name = 'equipo_logo' AND column_name = 'id_logo') THEN
    IF EXISTS (SELECT 1 FROM public.equipo_logo) THEN
      RAISE EXCEPTION 'equipo_logo (primera versión) tiene filas: migrarlas a mano antes de seguir';
    END IF;
    DROP TABLE public.equipo_logo;
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.equipo_logo (
    id_logo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_equipo BIGINT NOT NULL REFERENCES public.equipo(id_equipo) ON DELETE CASCADE,
    contenido BYTEA NOT NULL,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('image/png', 'image/jpeg', 'image/webp')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_equipo_logo_equipo ON public.equipo_logo(id_equipo);
ALTER TABLE public.equipo_logo ENABLE ROW LEVEL SECURITY;
`;

async function main() {
  const pool = getPool();
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query(migration);
    const { rowCount } = await client.query(
      `UPDATE public.equipo SET logo_url = NULL, updated_at = NOW() WHERE logo_url = '/gemini-svg.svg'`
    );
    await client.query('COMMIT');
    console.log(`Migración aplicada. Equipos pasados a escudo por defecto: ${rowCount}.`);
  } catch (err) {
    await client.query('ROLLBACK');
    throw err;
  } finally {
    client.release();
    await pool.end();
  }
}

main().catch((err) => {
  console.error('Error en la migración:', err.message);
  process.exit(1);
});
