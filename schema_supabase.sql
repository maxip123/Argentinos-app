-- 1. Vista: Próximos Partidos (con detección automática de partidos de Argentinos del Norte)
CREATE OR REPLACE VIEW public.vista_proximos_partidos 
WITH (security_invoker = true) AS
SELECT 
    p.id_partido,
    p.id_division,
    d.nombre_division,
    p.fecha_partido,
    p.jornada_numero,
    p.nombre_partido,
    p.id_sede,
    s.nombre_sede,
    s.direccion AS direccion_sede,
    s.google_maps_url,
    p.id_equipo_local,
    el.nombre_equipo AS equipo_local,
    el.logo_url AS logo_local,
    el.es_argentinos_del_norte AS local_es_argentinos,
    p.id_equipo_visitante,
    ev.nombre_equipo AS equipo_visitante,
    ev.logo_url AS logo_visitante,
    ev.es_argentinos_del_norte AS visitante_es_argentinos,
    (el.es_argentinos_del_norte OR ev.es_argentinos_del_norte) AS juega_argentinos_del_norte,
    p.estado_partido
FROM public.partido p
INNER JOIN public.division d ON d.id_division = p.id_division
INNER JOIN public.sede s ON s.id_sede = p.id_sede
INNER JOIN public.equipo el ON el.id_equipo = p.id_equipo_local
INNER JOIN public.equipo ev ON ev.id_equipo = p.id_equipo_visitante
WHERE p.activo = TRUE 
  AND p.estado_partido IN (0, 1)
ORDER BY p.fecha_partido ASC;

-- 2. Vista: Tabla de Posiciones
CREATE OR REPLACE VIEW public.vista_tabla_posiciones 
WITH (security_invoker = true) AS
SELECT 
    c.id_clasificacion,
    c.id_division,
    d.nombre_division,
    c.id_equipo,
    e.nombre_equipo,
    e.nombre_corto,
    e.logo_url,
    e.es_argentinos_del_norte,
    c.puntos,
    c.partidos_jugados,
    c.partidos_ganados,
    c.partidos_empatados,
    c.partidos_perdidos,
    c.goles_a_favor,
    c.goles_en_contra,
    c.diferencia_gol
FROM public.clasificacion c
INNER JOIN public.division d ON d.id_division = c.id_division
INNER JOIN public.equipo e ON e.id_equipo = c.id_equipo
WHERE c.activo = TRUE
ORDER BY c.id_division, c.puntos DESC, c.diferencia_gol DESC, c.goles_a_favor DESC;

-- 3. Vista: Tabla de Goleadores (Permite filtrar todos o solo Argentinos del Norte)
CREATE OR REPLACE VIEW public.vista_goleadores 
WITH (security_invoker = true) AS
SELECT 
    j.id_jugador,
    j.nombre,
    j.apellido,
    CONCAT(j.apellido, ', ', j.nombre) AS nombre_completo,
    j.foto_url,
    j.id_division,
    d.nombre_division,
    j.id_equipo,
    e.nombre_equipo,
    e.es_argentinos_del_norte,
    j.es_jugador_club,
    j.goles_totales AS goles
FROM public.jugador j
INNER JOIN public.equipo e ON e.id_equipo = j.id_equipo
INNER JOIN public.division d ON d.id_division = j.id_division
WHERE j.activo = TRUE
ORDER BY j.id_division, j.goles_totales DESC;

-- 4. Vista: Tarjetas de Jugadores (Control disciplinario de Argentinos del Norte)
CREATE OR REPLACE VIEW public.vista_tarjetas 
WITH (security_invoker = true) AS
SELECT 
    j.id_jugador,
    j.nombre,
    j.apellido,
    CONCAT(j.apellido, ', ', j.nombre) AS nombre_completo,
    j.id_division,
    d.nombre_division,
    j.id_equipo,
    e.nombre_equipo,
    e.es_argentinos_del_norte,
    j.es_jugador_club,
    j.amarillas_totales AS amarillas,
    j.rojas_totales AS rojas
FROM public.jugador j
INNER JOIN public.equipo e ON e.id_equipo = j.id_equipo
INNER JOIN public.division d ON d.id_division = j.id_division
WHERE j.activo = TRUE
ORDER BY j.id_division, j.rojas_totales DESC, j.amarillas_totales DESC;

-- 5. Vista: Control de Cuotas para Tesorería
CREATE OR REPLACE VIEW public.vista_estado_cuotas 
WITH (security_invoker = true) AS
SELECT 
    c.id_cuota,
    j.id_jugador,
    CONCAT(j.apellido, ', ', j.nombre) AS jugador_nombre_completo,
    j.dni,
    j.telefono,
    d.id_division,
    d.nombre_division,
    e.nombre_equipo,
    c.periodo_mes,
    c.periodo_anio,
    c.monto_esperado,
    c.monto_abonado,
    (c.monto_esperado - c.monto_abonado) AS saldo_pendiente,
    c.fecha_vencimiento,
    c.fecha_pago,
    c.estado_pago,
    c.metodo_pago,
    c.comprobante_url
FROM public.cuota_jugador c
INNER JOIN public.jugador j ON j.id_jugador = c.id_jugador
INNER JOIN public.division d ON d.id_division = c.id_division
INNER JOIN public.equipo e ON e.id_equipo = j.id_equipo
WHERE c.activo = TRUE AND j.es_jugador_club = TRUE
ORDER BY c.periodo_anio DESC, c.periodo_mes DESC, j.apellido ASC;

