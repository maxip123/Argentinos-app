-- 2. Índices Parciales (Aceleran filtros recurrentes reduciendo tamaño en disco)
-- Equipos de Argentinos del Norte
CREATE INDEX IF NOT EXISTS idx_equipo_argentinos_activo 
    ON public.equipo(id_division) 
    WHERE es_argentinos_del_norte = TRUE AND activo = TRUE;

-- Jugadores activos de Argentinos del Norte
CREATE INDEX IF NOT EXISTS idx_jugador_club_activo 
    ON public.jugador(id_division, id_equipo) 
    WHERE es_jugador_club = TRUE AND activo = TRUE;

-- Próximos partidos pendientes de disputarse
CREATE INDEX IF NOT EXISTS idx_partido_proximos 
    ON public.partido(fecha_partido ASC, id_division) 
    WHERE estado_partido IN (0, 1) AND activo = TRUE;

-- Cuotas pendientes o vencidas (ideal para panel de Tesorería)
CREATE INDEX IF NOT EXISTS idx_cuota_morosos 
    ON public.cuota_jugador(id_division, fecha_vencimiento) 
    WHERE estado_pago IN ('Pendiente', 'Vencido', 'Parcial') AND activo = TRUE;

-- 3. Índices Covering con INCLUDE (Permiten Index-Only Scan)
-- Tabla de posiciones: consulta ultra rápida sin acceder al heap de la tabla
CREATE INDEX IF NOT EXISTS idx_clasificacion_covering 
    ON public.clasificacion(id_division, puntos DESC, diferencia_gol DESC, goles_a_favor DESC)
    INCLUDE (id_equipo, partidos_jugados, partidos_ganados, partidos_empatados, partidos_perdidos, goles_en_contra);

-- Goleadores: index-only scan para la tabla de goleadores
CREATE INDEX IF NOT EXISTS idx_jugador_goleadores_covering 
    ON public.jugador(id_division, goles_totales DESC)
    INCLUDE (id_equipo, nombre, apellido, foto_url, es_jugador_club)
    WHERE activo = TRUE;

-- 4. Índices GIN Trigram para Autocompletar / Buscador difuso
CREATE INDEX IF NOT EXISTS idx_jugador_busqueda_trgm 
    ON public.jugador USING gin ((nombre || ' ' || apellido) gin_trgm_ops);

CREATE INDEX IF NOT EXISTS idx_equipo_busqueda_trgm 
    ON public.equipo USING gin (nombre_equipo gin_trgm_ops);

