-- ==============================================================================
-- PROYECTO: CLUB ARGENTINOS DEL NORTE
-- ARQUITECTURA DE BASE DE DATOS: SUPABASE (POSTGRESQL 15+)
-- Diseñado siguiendo estándares de la skill 'postgres-pro':
-- - B-tree, Partial, Covering (INCLUDE) y GIN Trigram Indexes para consultas de alto rendimiento
-- - Row Level Security (RLS) habilitado con políticas de lectura pública y escritura autenticada
-- - Triggers automáticos para 'updated_at' y recálculo de tabla de posiciones
-- - Tipos canónicos: TIMESTAMPTZ, NUMERIC, CHECK constraints, JSONB para extensibilidad
-- - Vistas SQL optimizadas con 'security_invoker = true'
-- ==============================================================================

-- ------------------------------------------------------------------------------
-- 0. EXTENSIONES RECOMENDADAS
-- ------------------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pg_trgm";       -- Para búsquedas difusas ultrarrápidas de nombres
CREATE EXTENSION IF NOT EXISTS "unaccent";      -- Para ignorar acentos en búsquedas

-- ------------------------------------------------------------------------------
-- 1. TABLA: division
-- Representa las categorías del torneo (Primera, Reserva, Sub-17, Femenino, etc.)
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.division (
    id_division BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_division VARCHAR(100) NOT NULL,
    categoria VARCHAR(50) DEFAULT 'Libre',
    genero VARCHAR(20) NOT NULL DEFAULT 'Masculino' CHECK (genero IN ('Masculino', 'Femenino')),
    temporada INT NOT NULL DEFAULT EXTRACT(YEAR FROM CURRENT_DATE),
    terminado BOOLEAN NOT NULL DEFAULT FALSE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_inicio DATE,
    fecha_fin DATE,
    id_equipo_campeon BIGINT, -- Clave foránea referenciada tras crear 'equipo'
    reglas JSONB DEFAULT '{"puntos_victoria": 3, "puntos_empate": 1, "puntos_derrota": 0}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 2. TABLA: sede
-- Canchas y estadios donde se disputan los partidos
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.sede (
    id_sede BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_sede VARCHAR(120) NOT NULL,
    direccion VARCHAR(200) NOT NULL,
    google_maps_url TEXT,
    es_sede_propia BOOLEAN NOT NULL DEFAULT FALSE, -- TRUE para el predio/cancha de Argentinos del Norte
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 3. TABLA: equipo
-- Equipos participantes por división.
-- IMPORTANTE: 'es_argentinos_del_norte' permite registrar múltiples equipos del club
-- en una misma división (ej: "Argentinos del Norte A" y "Argentinos del Norte B").
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.equipo (
    id_equipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_division BIGINT NOT NULL REFERENCES public.division(id_division) ON DELETE RESTRICT,
    nombre_equipo VARCHAR(120) NOT NULL,
    nombre_corto VARCHAR(30),
    logo_url TEXT,
    es_argentinos_del_norte BOOLEAN NOT NULL DEFAULT FALSE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_equipo_division_nombre UNIQUE (id_division, nombre_equipo)
);

-- Clave foránea diferida para la división
ALTER TABLE public.division
    DROP CONSTRAINT IF EXISTS fk_division_equipo_campeon,
    ADD CONSTRAINT fk_division_equipo_campeon FOREIGN KEY (id_equipo_campeon) REFERENCES public.equipo(id_equipo) ON DELETE SET NULL;

-- ------------------------------------------------------------------------------
-- 4. TABLA: jugador
-- Ficha de jugadores. Contiene identificador del club y acumuladores rápidos
-- compatibles con el sistema previo de AFA.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.jugador (
    id_jugador BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_equipo BIGINT NOT NULL REFERENCES public.equipo(id_equipo) ON DELETE RESTRICT,
    id_division BIGINT NOT NULL REFERENCES public.division(id_division) ON DELETE RESTRICT,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    dni VARCHAR(30) NOT NULL,
    fecha_nacimiento DATE,
    telefono VARCHAR(50),
    email VARCHAR(150),
    foto_url TEXT,
    es_jugador_club BOOLEAN NOT NULL DEFAULT TRUE, -- TRUE para jugadores propios de Argentinos del Norte
    
    -- Acumuladores rápidos denormalizados (mantenidos para compatibilidad instantánea)
    goles_totales INT NOT NULL DEFAULT 0 CHECK (goles_totales >= 0),
    amarillas_totales INT NOT NULL DEFAULT 0 CHECK (amarillas_totales >= 0),
    rojas_totales INT NOT NULL DEFAULT 0 CHECK (rojas_totales >= 0),
    partidos_jugados INT NOT NULL DEFAULT 0 CHECK (partidos_jugados >= 0),
    
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_jugador_dni_division UNIQUE (dni, id_division)
);

-- ------------------------------------------------------------------------------
-- 5. TABLA: cuerpo_tecnico
-- Integrantes de cuerpo técnico por equipo
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.cuerpo_tecnico (
    id_cuerpo_tecnico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_equipo BIGINT NOT NULL REFERENCES public.equipo(id_equipo) ON DELETE CASCADE,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    dni VARCHAR(30),
    telefono VARCHAR(50),
    email VARCHAR(150),
    es_club BOOLEAN NOT NULL DEFAULT TRUE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 6. TABLA: cuota_jugador (CONTROL DE CUOTAS Y TESORERÍA)
-- Módulo financiero esencial para Argentinos del Norte
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.cuota_jugador (
    id_cuota BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_jugador BIGINT NOT NULL REFERENCES public.jugador(id_jugador) ON DELETE RESTRICT,
    id_division BIGINT NOT NULL REFERENCES public.division(id_division) ON DELETE RESTRICT,
    periodo_mes INT NOT NULL CHECK (periodo_mes BETWEEN 1 AND 12),
    periodo_anio INT NOT NULL CHECK (periodo_anio >= 2020),
    monto_esperado NUMERIC(12, 2) NOT NULL DEFAULT 0.00 CHECK (monto_esperado >= 0),
    monto_abonado NUMERIC(12, 2) NOT NULL DEFAULT 0.00 CHECK (monto_abonado >= 0),
    fecha_vencimiento DATE NOT NULL,
    fecha_pago TIMESTAMPTZ,
    estado_pago VARCHAR(25) NOT NULL DEFAULT 'Pendiente' CHECK (estado_pago IN ('Pendiente', 'Pagado', 'Parcial', 'Vencido', 'Exonerado/Becado')),
    metodo_pago VARCHAR(50) CHECK (metodo_pago IN ('Efectivo', 'Transferencia', 'MercadoPago', 'Débito', 'Crédito', 'Otro')),
    comprobante_url TEXT,
    transaccion_id VARCHAR(100),
    observaciones TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_cuota_jugador_periodo UNIQUE (id_jugador, periodo_mes, periodo_anio)
);

-- ------------------------------------------------------------------------------
-- 7. TABLA: partido
-- Fixture y resultados con estados estandarizados
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.partido (
    id_partido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_division BIGINT NOT NULL REFERENCES public.division(id_division) ON DELETE RESTRICT,
    id_sede BIGINT NOT NULL REFERENCES public.sede(id_sede) ON DELETE RESTRICT,
    id_equipo_local BIGINT NOT NULL REFERENCES public.equipo(id_equipo) ON DELETE RESTRICT,
    id_equipo_visitante BIGINT NOT NULL REFERENCES public.equipo(id_equipo) ON DELETE RESTRICT,
    fecha_partido TIMESTAMPTZ NOT NULL,
    jornada_numero INT CHECK (jornada_numero > 0),
    nombre_partido VARCHAR(100), -- Ej: 'Fecha 3 - Interzonal'
    goles_local INT NOT NULL DEFAULT 0 CHECK (goles_local >= 0),
    goles_visitante INT NOT NULL DEFAULT 0 CHECK (goles_visitante >= 0),
    
    -- Estados del partido:
    -- 0 = Programado / Próximo
    -- 1 = En Vivo / En Juego
    -- 2 = Finalizado
    -- 3 = Suspendido / Postergado
    -- 4 = Cancelado
    estado_partido INT NOT NULL DEFAULT 0 CHECK (estado_partido IN (0, 1, 2, 3, 4)),
    afecta_clasificacion BOOLEAN NOT NULL DEFAULT TRUE,
    datos_adicionales JSONB DEFAULT '{}'::jsonb, -- Árbitros, planillero, clima, incidencias
    observaciones TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_partido_equipos_distintos CHECK (id_equipo_local <> id_equipo_visitante)
);

-- ------------------------------------------------------------------------------
-- 8. TABLA: partido_estadistica_jugador (DETALLE POR PARTIDO)
-- Registra goles y tarjetas individuales de cada partido para auditoría exacta
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.partido_estadistica_jugador (
    id_estadistica BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_partido BIGINT NOT NULL REFERENCES public.partido(id_partido) ON DELETE CASCADE,
    id_jugador BIGINT NOT NULL REFERENCES public.jugador(id_jugador) ON DELETE RESTRICT,
    id_equipo BIGINT NOT NULL REFERENCES public.equipo(id_equipo) ON DELETE RESTRICT,
    goles INT NOT NULL DEFAULT 0 CHECK (goles >= 0),
    tarjetas_amarillas INT NOT NULL DEFAULT 0 CHECK (tarjetas_amarillas BETWEEN 0 AND 2),
    tarjetas_rojas INT NOT NULL DEFAULT 0 CHECK (tarjetas_rojas BETWEEN 0 AND 1),
    minutos_jugados INT CHECK (minutos_jugados >= 0),
    es_titular BOOLEAN NOT NULL DEFAULT TRUE,
    asistencias INT NOT NULL DEFAULT 0 CHECK (asistencias >= 0),
    observacion VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_partido_jugador UNIQUE (id_partido, id_jugador)
);

-- ------------------------------------------------------------------------------
-- 9. TABLA: sancion_jugador (TRIBUNAL DE DISCIPLINA / SUSPENSIONES)
-- Control de suspensiones por acumulación de amarillas o tarjetas rojas
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.sancion_jugador (
    id_sancion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_jugador BIGINT NOT NULL REFERENCES public.jugador(id_jugador) ON DELETE CASCADE,
    id_partido_origen BIGINT REFERENCES public.partido(id_partido) ON DELETE SET NULL,
    motivo VARCHAR(150) NOT NULL,
    fechas_suspension INT NOT NULL DEFAULT 1 CHECK (fechas_suspension >= 1),
    fechas_cumplidas INT NOT NULL DEFAULT 0 CHECK (fechas_cumplidas >= 0),
    cumplida BOOLEAN GENERATED ALWAYS AS (fechas_cumplidas >= fechas_suspension) STORED,
    observaciones TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 10. TABLA: clasificacion (TABLA DE POSICIONES)
-- Con columna calculada automática para diferencia de gol
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.clasificacion (
    id_clasificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_division BIGINT NOT NULL REFERENCES public.division(id_division) ON DELETE CASCADE,
    id_equipo BIGINT NOT NULL REFERENCES public.equipo(id_equipo) ON DELETE CASCADE,
    puntos INT NOT NULL DEFAULT 0,
    partidos_jugados INT NOT NULL DEFAULT 0,
    partidos_ganados INT NOT NULL DEFAULT 0,
    partidos_empatados INT NOT NULL DEFAULT 0,
    partidos_perdidos INT NOT NULL DEFAULT 0,
    goles_a_favor INT NOT NULL DEFAULT 0,
    goles_en_contra INT NOT NULL DEFAULT 0,
    diferencia_gol INT GENERATED ALWAYS AS (goles_a_favor - goles_en_contra) STORED,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_clasificacion_division_equipo UNIQUE (id_division, id_equipo)
);

-- ------------------------------------------------------------------------------
-- 11. TABLA: llave_playoff (CRUCES ELIMINATORIOS)
-- Soporta playoffs, penales y avance automático
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.llave_playoff (
    id_llave BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_division BIGINT NOT NULL REFERENCES public.division(id_division) ON DELETE CASCADE,
    fase VARCHAR(50) NOT NULL, -- '32avos', '16avos', 'Octavos', 'Cuartos', 'Semifinal', 'Final', 'Tercer Puesto'
    orden INT NOT NULL,
    id_equipo_local BIGINT REFERENCES public.equipo(id_equipo) ON DELETE SET NULL,
    id_equipo_visitante BIGINT REFERENCES public.equipo(id_equipo) ON DELETE SET NULL,
    goles_local INT,
    goles_visitante INT,
    penales_local INT,
    penales_visitante INT,
    id_partido BIGINT REFERENCES public.partido(id_partido) ON DELETE SET NULL,
    estado_partido INT NOT NULL DEFAULT 0 CHECK (estado_partido IN (0, 1, 2, 3, 4)),
    id_llave_siguiente BIGINT REFERENCES public.llave_playoff(id_llave) ON DELETE SET NULL,
    es_local_siguiente BOOLEAN NOT NULL DEFAULT TRUE,
    id_equipo_ganador BIGINT REFERENCES public.equipo(id_equipo) ON DELETE SET NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

